-- Etapa 1: catálogo de produtos

CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL REFERENCES public.categorias(id),
    nome TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    marca TEXT,
    descricao TEXT,
    preco NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
    preco_antigo NUMERIC(10,2),
    estoque INTEGER NOT NULL DEFAULT 0 CHECK (estoque >= 0),
    imagem_url TEXT,
    selo TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Habilitar segurança por linha (RLS)
ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.produtos ENABLE ROW LEVEL SECURITY;

-- Permitir leitura pública do catálogo
DROP POLICY IF EXISTS "leitura_categorias" ON public.categorias;
CREATE POLICY "leitura_categorias"
ON public.categorias FOR SELECT
TO anon, authenticated
USING (true);

DROP POLICY IF EXISTS "leitura_produtos" ON public.produtos;
CREATE POLICY "leitura_produtos"
ON public.produtos FOR SELECT
TO anon, authenticated
USING (ativo = true);

GRANT SELECT ON public.categorias, public.produtos
TO anon, authenticated;

-- Bloquear alterações diretas pelo navegador
REVOKE INSERT, UPDATE, DELETE
ON public.categorias, public.produtos
FROM anon, authenticated;

